"""
A greeting clip for a personal website, made end to end by this project:
text -> Kokoro voice -> EMAGE gestures -> motion_post (idle lead-in and
tail, x0.7 gestures, gaze) -> render with face_export.py.

Two stages, because Kokoro lives in the base env and EMAGE in pantomatrix:

    # base env
    python make_greeting.py tts --text "Hi, welcome to ..." --out /root/greeting
    # pantomatrix env
    python make_greeting.py motion --out /root/greeting
    python face_export.py /root/greeting/greeting.npz --audio /root/greeting/greeting.wav \\
        --keep-root --view upper --label "" --size 1080

make_greeting.sh runs all three.
"""
import argparse
from pathlib import Path

import numpy as np

DEFAULT_TEXT = ("Hi there, and welcome to Keyi's website! "
                "I'm a digital human that Keyi built. "
                "My voice, my gestures, and even where I look are all generated by AI, "
                "straight from speech. "
                "Have a look around, and thanks for stopping by!")

ap = argparse.ArgumentParser()
ap.add_argument("stage", choices=["tts", "motion"])
ap.add_argument("--text", default=DEFAULT_TEXT)
ap.add_argument("--voice", default="af_heart",
                help="Kokoro voice: af_heart, af_bella, af_nicole, af_sarah, am_michael, bf_emma ...")
ap.add_argument("--out", default="/root/greeting")
ap.add_argument("--lead", type=float, default=1.0, help="seconds of idle before speaking")
ap.add_argument("--tail", type=float, default=2.5, help="seconds of idle after speaking")
ap.add_argument("--scale", type=float, default=0.7, help="gesture size")
ap.add_argument("--look", type=float, default=0.85,
                help="share of time the eyes are on the viewer (rest: brief look-aways)")
ap.add_argument("--seed", type=int, default=3)
ap.add_argument("--repo", default="/root/PantoMatrix")
ap.add_argument("--weights", default="/root/emage_weights")
args = ap.parse_args()
out = Path(args.out)
out.mkdir(parents=True, exist_ok=True)
SPEECH = out / "greeting_speech.wav"
TTS_SR = 24000

if args.stage == "tts":
    import soundfile as sf
    from kokoro import KPipeline
    pipe = KPipeline(lang_code=args.voice[0])          # 'a' American, 'b' British
    chunks = [np.asarray(a, np.float32) for _, _, a in pipe(args.text, voice=args.voice)]
    gap = np.zeros(int(0.12 * TTS_SR), np.float32)      # Kokoro splits at sentences
    audio = np.concatenate([x for c in chunks for x in (c, gap)][:-1])
    sf.write(SPEECH, audio, TTS_SR)
    print(f"  {SPEECH}  {len(audio) / TTS_SR:.1f}s  voice {args.voice}")
    raise SystemExit(0)

# --- motion -------------------------------------------------------------------
import librosa  # noqa: E402
import soundfile as sf  # noqa: E402

import motion_post as mp  # noqa: E402
from evaluate_shortcomings import load_emage, save_emage_npz, make_gaze  # noqa: E402

FPS = mp.FPS
if not SPEECH.exists():
    raise SystemExit(f"{SPEECH} missing — run the tts stage first (base env)")

print("loading EMAGE…")
gen, sr = load_emage(Path(args.repo), Path(args.weights))

# Rest pose from a long clip, the same way emage_server does. (The example
# audio is only used to find a natural standing pose; it is not in the output.)
example = Path(args.repo) / "examples" / "audio" / "2_scott_0_103_103_28s.wav"
ref_audio, _ = librosa.load(str(example), sr=sr)
rest = mp.rest_pose_from(gen(ref_audio)[0])

speech16, _ = librosa.load(str(SPEECH), sr=sr)
poses, expr, _ = gen(speech16)
print(f"  speech {len(speech16) / sr:.1f}s -> {len(poses)} frames")

s = mp.Session(rest, scale=args.scale, seed=args.seed)
lead = s.idle(int(args.lead * FPS))
talk = s.speak(poses, expr)
tail = s.idle(int(args.tail * FPS))
P = np.concatenate([lead[0], talk[0], tail[0]])
E = np.concatenate([lead[1], talk[1], tail[1]])

# Eyes: mostly on the viewer, with short look-aways while talking.
gaze, fix, clamp = make_gaze(P, seed=args.seed, look_ratio=args.look, include_root=True)
P[:, 69:72] = gaze
P[:, 72:75] = gaze
print(f"  gaze: {len(fix)} fixations, {sum(f['kind'] == 'away' for f in fix)} look-aways, "
      f"{clamp:.0%} frames at the eye limit")

save_emage_npz(out / "greeting.npz", P, E, np.zeros((len(P), 3)))

# "Before", for the comparison video: the same EMAGE output with nothing
# added — the avatar holds its first frame until speech starts and its last
# frame after it ends (what the live system did between sentences), full-size
# gestures, eyes fixed. Same length and soundtrack as "after".
nl, nt = len(lead[0]), len(tail[0])
B = np.concatenate([np.tile(poses[:1], (nl, 1)), poses, np.tile(poses[-1:], (nt, 1))])
BE = np.concatenate([np.tile(expr[:1], (nl, 1)), expr, np.tile(expr[-1:], (nt, 1))])
assert len(B) == len(P)
save_emage_npz(out / "greeting_raw.npz", B, BE, np.zeros((len(B), 3)))

# Soundtrack aligned to the frames: silence for the lead, speech, silence for the tail.
speech24, _ = librosa.load(str(SPEECH), sr=TTS_SR)
track = np.zeros(int(round(len(P) / FPS * TTS_SR)), np.float32)
start = int(round(len(lead[0]) / FPS * TTS_SR))
seg = speech24[:max(0, len(track) - start)]
track[start:start + len(seg)] = seg
sf.write(out / "greeting.wav", track, TTS_SR)
print(f"  {out}/greeting.npz  greeting_raw.npz  greeting.wav  ({len(P) / FPS:.1f}s)")
